function renderConcept(book, concept, next, index, level, family) {
  const [nameRaw, explainRaw, useRaw, boundaryRaw] = concept;
  const name = trimStop(nameRaw);
  const explain = trimStop(explainRaw);
  const use = trimStop(useRaw);
  const boundary = trimStop(boundaryRaw);
  const nextName = next ? safeText(next[0]) : "整本书的最终判断";
  const lenses = conceptLenses[family];
  const leads = index === 0 ? [
    `全书先用“${name}”固定分析对象。${explain}。这一定义决定后文能够讨论哪些状态、操作和保证。`,
  ] : [
    `“${name}”承接前面已经建立的对象关系。${explain}。这里新增的规则会改变后续能够作出的判断。`,
    `到了“${name}”，原书开始处理上一环尚未解决的困难。${explain}。理解它需要同时保留前一节的输入与限制。`,
    `接下来要处理“${name}”。${explain}。这一步把先前的局部结论送进更完整的执行或验证过程。`,
    `原书随后把视线转向“${name}”。${explain}。它补上的关系，正是后一部分能够继续推理的前提。`,
  ];
  const lead = leads[index === 0 ? 0 : (index - 1) % leads.length];
  const method = `${use}。${lenses[index % lenses.length]}`;
  const endings = [
    `在“${trimStop(book.caseHeading)}”中验证这项知识时，应留下${conceptArtifacts[family]}。${boundary}。带着这项限制进入“${trimStop(nextName)}”，后面的结论才有清楚前提。`,
    `实践记录需要说明“${name}”在正常条件下产生什么结果，并主动加入一个边界条件。${boundary}。若结果随之改变，就把差异带到“${trimStop(nextName)}”继续处理。`,
    `这一节适合产出${conceptArtifacts[family]}，让另一位读者能够复查选择。${boundary}。尚未覆盖的输入、状态与环境，应在进入“${trimStop(nextName)}”时继续保留。`,
    `把“${name}”用于当前项目时，先写明成立条件，再保留能够推翻结论的反例。${boundary}。下一节“${trimStop(nextName)}”要接住这项未解决的问题。`,
  ];
  const ending = endings[index % endings.length];
  const mark = "#".repeat(level);
  return `${mark} ${name}\n\n${lead}\n\n${method}\n\n${ending}\n`;
}

function renderConcepts(book, family) {
  const meta = familyMeta[family];
  const splitAt = Math.ceil(book.concepts.length / 2);
  const first = book.concepts.slice(0, splitAt).map((concept, index) => renderConcept(book, concept, book.concepts[index + 1], index, 3, family)).join("\n");
  const second = book.concepts.slice(splitAt).map((concept, offset) => {
    const index = splitAt + offset;
    return renderConcept(book, concept, book.concepts[index + 1], index, 3, family);
  }).join("\n");
  return `## ${meta.groups[0]}\n\n${first}\n## ${meta.groups[1]}\n\n${second}`;
}

function renderBridges(book) {
  return book.concepts.slice(0, -1).map((concept, index) => {
    const next = book.concepts[index + 1];
    const [name, explain, , boundary] = concept.map(safeText);
    const [nextName, nextExplain] = next.map(safeText);
    const leads = ["前一节定义对象，后一节增加机制", "前一节给出局部保证，后一节处理剩余限制", "前一节留下可观察状态，后一节利用这些状态作选择"];
    return `从“${name}”走到“${nextName}”时，${leads[index % leads.length]}。${explain}，随后${nextExplain}。两节之间传递的是仍带适用条件的判断。读者应确认前一节的输出能被后一节读取，也要保留“${boundary}”这项限制。若衔接只能靠经验猜测，项目里就需要补一份接口说明、测试、证明或运行记录。`;
  }).join("\n\n");
}

function renderSynthesis(book, family) {
  const first = book.concepts[0].map(trimStop);
  const middle = book.concepts[Math.floor(book.concepts.length / 2)].map(trimStop);
  const last = book.concepts.at(-1).map(trimStop);
  return `单独理解“${first[0]}”只能得到全书的入口。它规定${first[1]}，随后“${middle[0]}”把问题推进到${middle[1]}。最后的“${last[0]}”继续处理${last[1]}。三者合在一起，才能说明这本书如何从对象定义走到完整结果，也能解释为什么章节次序不能随意打乱。

复述这条主线时，应把${conceptArtifacts[family]}放在旁边。读者需要指出前一环产生了什么，后一环怎样使用，以及哪个条件变化会使传递中断。若“${middle[0]}”无法读取“${first[0]}”留下的信息，说明中间还缺接口、状态或证据；若“${last[0]}”没有接住“${middle[0]}”暴露的限制，阅读就停在了局部技巧。

这条主线也提供了删减标准。与“${first[0]}”到“${last[0]}”无关的细节可以稍后查阅，会改变这条因果关系的定义、机制和反例则应当精读。这样安排既能保留《${safeText(book.title)}》的专业密度，也能避免第一次阅读被所有章节和术语同时淹没。`;
}

