function safeText(text) {
  return text
    .replaceAll("—", "，")
    .replaceAll("–", "至")
    .replaceAll("真正", "明确")
    .replace(/不是([^，。]{1,28})，而是/g, "重点不只在$1，也在")
    .replace(/并非([^，。]{1,28})，而是/g, "既不止于$1，也包含");
}

function trimStop(text) {
  return safeText(text).replace(/[。；，！？]+$/u, "");
}

