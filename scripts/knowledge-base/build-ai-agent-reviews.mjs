function renderTopic(topic, index, shape) {
  const [heading, meaning, method, agent, pitfall] = topic;
  const openings = [
    `这一节先处理${meaning}。概念落到模型里，需要同时说明输入怎样表示、输出受什么约束，以及结果怎样被检查。`,
    `${heading}决定后续方法能否站稳。${meaning}。读者应先把这里的假设写清，再进入公式或代码。`,
    `作者在这里关注${meaning}。这一步把一个宽泛问题缩成能够训练、推断或验证的对象。`,
    `理解这一部分，可以从一个具体判断开始。${meaning}。条件改变以后，原有算法的结论也会跟着改变。`,
  ];
  const methods = [
    `${method}。这种安排让方法的适用条件显形，也让不同模型能够在同一问题上比较。`,
    `${method}。书中的推导服务于这个关系，公式负责保留条件，例子负责展示条件变化后的结果。`,
    `${method}。阅读时可以沿着数据、表示、目标和计算过程重画一遍，概念会比孤立记定义更牢。`,
    `${method}。前后章节的连接也在这里形成，上一章提供表示，本章说明怎样利用，下一章再处理它留下的限制。`,
  ];
  const applications = [
    `${agent}。把它放进 AI 应用评审时，还应写出负责组件、可观察指标和失败后的接管方式。`,
    `${agent}。这项迁移要求保留原书的假设，不能因为换成大语言模型就省略环境状态与评价标准。`,
    `${agent}。工程上至少要留下输入样本、运行轨迹和结果证据，才能知道改动是否真的有效。`,
    `${agent}。它给出的首先是一种判断方法，具体实现仍要受延迟、成本、权限和数据可得性约束。`,
  ];
  const cautions = [
    `${pitfall}。出现异常时，应回到本节的对象与假设排查，继续更换模型通常不能消除定义上的错误。`,
    `${pitfall}。这种错误常在离线样本里不明显，进入新分布或长任务以后才集中暴露。`,
    `${pitfall}。因此，本节知识最终应沉淀成一条可以复查的设计约束，而不只是一个术语。`,
    `${pitfall}。读者若能说清这条边界，就已经抓住本节对系统判断最有用的部分。`,
  ];
  const checks = [
    `把本节变成练习，可以固定一份输入，逐项改变${meaning}中的一个条件，随后比较结果、资源消耗和错误类型。${method}，所以观察项也应沿着同一关系设置。`,
    `真正应用时，可以先做一个最小对照。保留旧方法作为基线，只引入本节讨论的变化，并记录它对正确性、稳定性和运行代价的影响。${agent}。`,
    `本节适合沉淀成设计记录。记录中写明采用这项方法的理由、被舍弃的方案、成立条件和回退办法。${pitfall}，这些信息能让后续维护者知道何时应重新评估。`,
    `读者还应检查概念的测量方式。训练指标、离线任务和真实运行各能看见一部分现象，三者的口径若不一致，${pitfall}。这时要先修正证据链。`,
  ];
  const i = index % openings.length;
  return `## ${heading}\n\n${openings[i]}\n\n${methods[(index + 1) % methods.length]}\n\n${applications[(index + 2) % applications.length]}\n\n${cautions[(index + 3) % cautions.length]}\n\n${checks[index % checks.length]}\n`;
}

function renderConnections(book) {
  const headings = {
    concept: "把前后章节连成一条推理链",
    workflow: "把各章接成一条工程链",
    decision: "把状态、行动与证据连起来",
    risk: "从一处风险追到系统边界",
  };
  const leads = ["第一遍走到", "继续进入", "随后来到", "再往后看", "最后回到"];
  const paragraphs = book.arc.map((stage, index) => {
    const first = book.topics[(index * 2) % book.topics.length];
    const second = book.topics[(index * 2 + 1) % book.topics.length];
    return `${leads[index] ?? "接着处理"}“${stage}”时，可以把“${first[0]}”与“${second[0]}”放在一起读。前者说明${first[1]}，后者继续处理${second[1]}。两章之间真正传递的是问题条件。条件若没有传过去，读者会记住两组名词，却看不见后一种方法为何出现。`;
  }).join("\n\n");
  const early = book.topics[1];
  const late = book.topics[book.topics.length - 2];
  return `## ${headings[book.shape ?? "concept"]}\n\n${paragraphs}\n\n完成这条连接后，再做一次反向检查。从“${late[0]}”往前追，找出它依赖的表示、数据与评价条件；再从“${early[0]}”往后追，查看这个基础概念在哪些后续章节被重新使用。能来回走通，说明知识已经形成结构。只会沿目录顺序复述，遇到新论文仍然很难判断它改动了哪一环。\n`;
}

