function renderExpansion(item) {
  const sections = item.headings.map((heading, i) => {
    const [object, method, boundary] = item.ideas[i];
    return `### ${heading}\n\n${object}。这一部分应与原书对应章节一起读，先确定作者处理的对象，再查看它怎样进入计算或实验。\n\n${method}。可以用一份小数据把过程从输入走到输出，记录每个中间结果。若只能复述结论，却无法指出数据在哪里变化，理解仍然停在术语层。\n\n${boundary}。把这条限制写进笔记，随后设计一个会触发它的反例。反例能帮助读者区分方法自身能力、数据覆盖和工程实现，后续读论文时也知道新工作究竟修正了哪一项。`;
  }).join("\n\n");
  return `${markerStart}\n\n## 在${item.field}模块中进一步读这本书\n\n同一本书进入不同学习模块，承担的任务会发生变化。下面几节补足它与${item.field}路线的连接，不重复前文书目信息，也不把原书章节改写成资料清单。每节都从一个可以判断的问题出发，并给出对应练习与边界。阅读时可以在纸上保留三栏，依次记录原书结论、本地例子和失败条件。这样增加的内容会回到具体判断，不会成为另一组悬空术语。\n\n${sections}\n\n## 补充阅读后的复盘问题\n\n1. 能否指出本书最稳定的三个概念，以及最容易随工具版本变化的部分。\n2. 能否选择一个方法，写清输入、输出、优化目标和独立评价。\n3. 能否找出一项平均指标看不见的失败，并设计数据切片。\n4. 能否说明本书没有覆盖的生产条件，需要用哪类资料补齐。\n\n四个问题都应落到一份样本、一次实验或一条设计记录。答案只有术语时，继续回到对应章节；答案包含对象、条件和证据时，这本书才真正进入学习路线。\n\n${markerEnd}`;
}

function cleanLegacyProse(content) {
  return content
    .replaceAll("两章之间真正传递的是", "两章之间传递的是")
    .replaceAll("真正应用时", "进入实际项目时")
    .replaceAll("真正掌握", "掌握")
    .replaceAll("沉淀成", "整理成")
    .replaceAll("沉淀为", "整理为")
    .replaceAll("沉淀", "保留")
    .replaceAll("链路", "过程")
    .replace(
      /读完以后，用本书自己的问题自测。能否用普通语言说明“([^”]+)”处理什么，能否指出“([^”]+)”成立的条件，能否给“([^”]+)”写出一个失败反例，随后把其中一项变成系统检查。/g,
      "读完以后，围绕本书完成三项自测。\n\n1. 用普通语言说明“$1”处理什么。\n2. 指出“$2”成立的条件。\n3. 给“$3”写出一个失败反例。\n\n随后把其中一项变成系统检查。",
    );
}

for (const item of reviews) {
  const file = path.resolve(item.file);
  let content = cleanLegacyProse(await readFile(file, "utf8"));
  const pattern = new RegExp(`${markerStart}[\\s\\S]*?${markerEnd}\\n*`, "g");
  content = content.replace(pattern, "").trimEnd();
  await writeFile(file, `${content}\n\n${renderExpansion(item)}\n`, "utf8");
}

for (const relativeFile of cleanupOnly) {
  const file = path.resolve(relativeFile);
  await writeFile(file, cleanLegacyProse(await readFile(file, "utf8")), "utf8");
}

console.log(`expanded ${reviews.length} shared reviews and cleaned ${cleanupOnly.length} reused reviews`);
