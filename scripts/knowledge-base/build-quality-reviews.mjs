function chineseCount(text) {
  return (text.match(/[\u3400-\u9fff]/g) ?? []).length;
}

function topicBody(topic, next, index, profile, level = 2) {
  const [heading, meaning, action, boundary] = topic;
  const nextHeading = next?.[0] ?? "最终决定";
  const variants = [
    [`这一部分先改变观察对象。${meaning}。因此，读者不能只记住“${heading}”这个名称，还要问它指向哪个工件、哪种状态和哪类失败。`, `${action}。实施时把责任人、输入、输出和检查位置同时写出，团队才知道这项要求怎样进入日常工作。`, `${boundary}。这条边界提醒我们，单项结果只覆盖有限条件。随后进入“${nextHeading}”时，前一节留下的对象与证据仍需继续使用。`],
    [`理解“${heading}”，可以从一次失败倒推。${meaning}。若这一关系没有被表达，团队通常会在结果异常后才发现定义缺口。`, `可执行的做法是${action}。它把抽象原则变成可以评审和复查的工程动作，也让后续变化有比较基线。`, `需要保留的限制是${boundary}。遇到不同环境、组织规模或风险等级时，应重新检查假设，不能只复用结论。`],
    [`本节解决的核心矛盾，是资源有限而判断需要证据。${meaning}。作者把问题放进完整工作过程，并联系上下游活动讨论工具。`, `${action}。这一步的产物应能被下一角色读取，并能说明当前已知信息和剩余未知。`, `${boundary}。忽略这项边界时，流程即使完成，团队仍无法回答是否应该继续交付。下一节“${nextHeading}”正是在这个基础上增加新的约束。`],
    [`在${profile.caseName}中，“${heading}”会直接影响设计与发布。${meaning}。同一句原则换到低风险内部工具上，所需证据可能明显减少。`, `团队可以先${action}，随后用一次真实变更检验记录是否足够支持复现、解释和处置。`, `${boundary}。好的实践会公开这种不确定性，让决定者知道结论覆盖到哪里。`],
  ];
  const paragraphs = variants[index % variants.length];
  const headingMark = "#".repeat(level);
  return `${headingMark} ${heading}\n\n${paragraphs[0]}\n\n${paragraphs[1]}\n\n${paragraphs[2]}\n\n放到${profile.caseName}中，可以把这项知识压成一次小型评审。先指出${meaning}，再落实“${action}”，并把产生的记录交给下一位需要作决定的人。评审结尾主动挑战结论，因为${boundary}。能够走完这几步，说明“${heading}”已经从知识名称进入工程判断。\n`;
}

function renderTopics(profile) {
  const grouped = {
    syllabus: ["先建立测试工作的基本坐标", "再把技术、管理和工具接起来", 3],
    handbook: ["从任务与要求开始", "让验证、保证和评审形成证据", 3],
    sre: ["先定义服务应维持的结果", "再处理运行、事故与组织学习", 3],
    observability: ["先建立信号和语义", "再进入查询、告警与运行治理", 4],
    framework: ["先准备风险判断所需条件", "再把控制、沟通与更新接起来", 3],
    security: ["先识别资产、入口与信任边界", "再沿攻击路径验证和处置", 3],
    platform: ["先理解声明、对象和用户任务", "再处理控制、运营和演进", 4],
    resilience: ["先建立实验假设", "再把扰动变成可复验的改进", 3],
  }[profile.kind];
  if (!grouped) {
    return profile.topics.map((topic, index) => topicBody(topic, profile.topics[index + 1], index, profile, 2)).join("\n");
  }
  const [firstTitle, secondTitle, splitAt] = grouped;
  const first = profile.topics.slice(0, splitAt).map((topic, index) => topicBody(topic, profile.topics[index + 1], index, profile, 3)).join("\n");
  const second = profile.topics.slice(splitAt).map((topic, offset) => {
    const index = splitAt + offset;
    return topicBody(topic, profile.topics[index + 1], index, profile, 3);
  }).join("\n");
  return `## ${firstTitle}\n\n${first}\n## ${secondTitle}\n\n${second}`;
}

function renderBridges(profile) {
  return profile.topics.slice(0, -1).map((topic, index) => {
    const next = profile.topics[index + 1];
    const turns = ["定义对象后才能选择方法", "形成方法后还要保存证据", "得到证据后才能支持决定", "进入下一环前要重新检查边界"];
    return `从“${topic[0]}”走向“${next[0]}”时，${turns[index % turns.length]}。前一节说明${topic[1]}，后一节继续处理${next[1]}。两者之间传递的是一项仍带着成立条件的工程判断，单个术语容纳不了这些信息。团队应检查前一节的输出是否成为后一节的输入，也要确认${topic[3]}。如果中间只能靠口头经验补齐，这里就是最值得建立记录、接口或自动检查的位置。`;
  }).join("\n\n");
}

